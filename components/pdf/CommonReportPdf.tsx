"use client";

import { Document, Image, Page, Text, View } from "@react-pdf/renderer";
import { format } from "date-fns";
import { styles } from "./style";
import { THEME } from "./theme";
import { CommonRoomLogResponse, CommonRoomResponse } from "@/types/dashboard.types";

const ROOMS_PER_PAGE = 10;
const ROWS_PER_PAGE = 24;

type NumericValue = number | string | null | undefined;

const CATEGORY_WITHOUT_RH = new Set([2, 3, 5]);

function hideRH(categoryId?: number | null): boolean {
  return categoryId != null && CATEGORY_WITHOUT_RH.has(categoryId);
}

type CommonReportFilter = {
  categoryName: string;
  interval: number;
  fromDate: string;
  toDate: string;
};

type CommonReportPDFProps = {
  data?: CommonRoomResponse[];
  filter: CommonReportFilter;
  name: string;
};

type SummaryType = "avg" | "min" | "max";

type SummaryRow = {
  label: string;
  type: SummaryType;
};

type ReportRow = {
  timeStamp?: string | number | Date;
  values: CommonRoomLogResponse[];
};

function formatStat(value: NumericValue, type: "temperature" | "rh"): string {
  if (value == null || value === "") return "-";

  const number = Number(value);

  if (!Number.isFinite(number)) return "-";

  if (type === "temperature") return number.toFixed(1);
  if (type === "rh") return String(Math.round(number));

  return String(number);
}

function formatDate(value: string | number | Date, pattern: string): string {
  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) return "-";

  return format(date, pattern);
}

const summaryRows: SummaryRow[] = [
  { label: "AVG", type: "avg" },
  { label: "MIN", type: "min" },
  { label: "MAX", type: "max" },
];

export default function CommonReportPDF({ data = [], filter, name }: CommonReportPDFProps): React.JSX.Element {
  if (!data.length) {
    return <Document />;
  }

  // Split rooms into groups of 10.
  const roomGroups: CommonRoomResponse[][] = [];

  for (let i = 0; i < data.length; i += ROOMS_PER_PAGE) {
    roomGroups.push(data.slice(i, i + ROOMS_PER_PAGE));
  }

  return (
    <Document>
      {roomGroups.map((rooms, groupIndex) => {
        const firstRoom = rooms[0];

        if (!firstRoom) return null;

        // Create rows from the first room's timestamps.
        const rows: ReportRow[] = firstRoom.logs.map((log, index) => ({
          timeStamp: log.timeStamp,
          values: rooms.map((room) => room.logs[index] ?? {}),
        }));

        // Split detail rows into pages.
        const pages: ReportRow[][] = [];

        for (let i = 0; i < rows.length; i += ROWS_PER_PAGE) {
          pages.push(rows.slice(i, i + ROWS_PER_PAGE));
        }

        return pages.map((pageRows, pageIndex) => (
          <Page key={`${groupIndex}-${pageIndex}`} size="A4" style={styles.page}>
            {/* HEADER */}
            <View style={styles.header}>
              <Image src="/logo.jpg" style={styles.icon} />

              <View style={{ alignItems: "flex-end" }}>
                <Text
                  style={{
                    fontSize: 10,
                    color: THEME.main,
                    fontWeight: "bold",
                  }}
                >
                  COLD STORAGE, JNPT, NAVI MUMBAI
                </Text>

                <Text style={{ fontSize: 9 }}>
                  {format(new Date(), "dd MMM yyyy")} - {format(new Date(), "hh:mm:ss a")}
                </Text>
              </View>
            </View>

            {/* REPORT DETAILS */}
            <Text style={styles.title}>Multiple Room</Text>

            <View style={styles.gridContainer}>
              <View style={styles.gridRow}>
                <Text style={styles.label}>Generated By : </Text>
                <Text>{name}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Category :</Text>
                <Text>{filter.categoryName}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Interval :</Text>
                <Text>{filter.interval} Minutes</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Duration :</Text>
                <Text>
                  {formatDate(filter.fromDate, "dd MMM yyyy hh:mm a")} - {formatDate(filter.toDate, "dd MMM yyyy hh:mm a")}
                </Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Rooms :</Text>
                <Text>{data.map((room) => room.roomName).join(", ")}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Records :</Text>
                <Text>{rows.length}</Text>
              </View>
            </View>

            {/* DETAIL LOG */}
            <Text
              style={{
                marginTop: 2,
                marginBottom: 2,
                fontSize: 12,
                fontWeight: "bold",
                color: THEME.main,
              }}
            >
              DETAIL LOG
            </Text>

            {/* TABLE */}
            <View
              style={{
                borderWidth: 1,
                borderColor: THEME.border,
              }}
            >
              {/* HEADER ROW 1: ROOM NAMES */}
              <View
                style={{
                  flexDirection: "row",
                  backgroundColor: THEME.main,
                  color: "#fff",
                  borderBottomWidth: 1,
                  borderColor: THEME.border,
                  minHeight: 20,
                }}
              >
                <View
                  style={{
                    width: 100,
                    justifyContent: "center",
                    alignItems: "center",
                    borderRightWidth: 1,
                    borderColor: "#fff",
                    paddingVertical: 8,
                  }}
                >
                  <Text
                    style={{
                      fontSize: 9,
                      fontWeight: "bold",
                    }}
                  >
                    DATETIME
                  </Text>
                </View>

                {rooms.map((room) => (
                  <View
                    key={room.roomId}
                    style={{
                      flex: hideRH(room.categoryId) ? 1 : 2,
                      justifyContent: "center",
                      alignItems: "center",
                      borderRightWidth: 1,
                      borderColor: "#fff",
                      paddingVertical: 8,
                    }}
                  >
                    <Text
                      style={{
                        fontSize: 9,
                        fontWeight: "bold",
                      }}
                    >
                      {room.roomName}
                    </Text>
                  </View>
                ))}
              </View>

              {/* HEADER ROW 2: TEMP / RH */}
              <View
                style={{
                  flexDirection: "row",
                  backgroundColor: THEME.main,
                  color: "#fff",
                  borderBottomWidth: 1,
                  borderColor: THEME.border,
                  minHeight: 20,
                }}
              >
                <View
                  style={{
                    width: 100,
                    borderRightWidth: 1,
                    borderColor: "#fff",
                  }}
                />

                {rooms.map((room) => {
                  const hide = hideRH(room.categoryId);

                  return (
                    <View
                      key={room.roomId}
                      style={{
                        flex: hide ? 1 : 2,
                        flexDirection: "row",
                        borderRightWidth: 1,
                        borderColor: "#fff",
                      }}
                    >
                      <View
                        style={{
                          flex: 1,
                          alignItems: "center",
                          borderRightWidth: hide ? 0 : 1,
                          borderColor: "#fff",
                          paddingVertical: 5,
                        }}
                      >
                        <Text style={{ fontSize: 8, fontWeight: "bold", textAlign: "center" }}>{"Temp\n°C"}</Text>
                      </View>

                      {!hide && (
                        <View style={{ flex: 1, alignItems: "center", paddingVertical: 5 }}>
                          <Text style={{ fontSize: 8, fontWeight: "bold", textAlign: "center" }}>{"RH\n%"}</Text>
                        </View>
                      )}
                    </View>
                  );
                })}
              </View>

              {/* AVG / MIN / MAX */}
              {summaryRows.map(({ label, type }) => (
                <View
                  key={label}
                  style={{
                    flexDirection: "row",
                    backgroundColor: THEME.main,
                    color: "#fff",
                    borderBottomWidth: 1,
                    borderColor: THEME.border,
                    minHeight: 20,
                  }}
                >
                  <View
                    style={{
                      width: 100,
                      justifyContent: "center",
                      alignItems: "center",
                      borderRightWidth: 1,
                      borderColor: "#fff",
                    }}
                  >
                    <Text
                      style={{
                        fontSize: 8,
                        fontWeight: "bold",
                      }}
                    >
                      {label}
                    </Text>
                  </View>

                  {rooms.map((room) => {
                    const temperatureKey = `${type}Temperature` as keyof CommonRoomResponse;
                    const humidityKey = `${type}Rh` as keyof CommonRoomResponse;
                    const hide = hideRH(room.categoryId);

                    return (
                      <View
                        key={room.roomId}
                        style={{
                          flex: hide ? 1 : 2,
                          flexDirection: "row",
                          borderRightWidth: 1,
                          borderColor: "#fff",
                        }}
                      >
                        <View
                          style={{
                            flex: 1,
                            alignItems: "center",
                            justifyContent: "center",
                            borderRightWidth: hide ? 0 : 1,
                            borderColor: "#fff",
                          }}
                        >
                          <Text
                            style={{
                              fontSize: 8,
                              fontWeight: "bold",
                            }}
                          >
                            {formatStat(room[temperatureKey] as NumericValue, "temperature")}
                          </Text>
                        </View>

                        {!hide && (
                          <View
                            style={{
                              flex: 1,
                              alignItems: "center",
                              justifyContent: "center",
                            }}
                          >
                            <Text style={{ fontSize: 8, fontWeight: "bold" }}>{formatStat(room[humidityKey] as NumericValue, "rh")}</Text>
                          </View>
                        )}
                      </View>
                    );
                  })}
                </View>
              ))}

              {/* BODY */}
              {pageRows.map((row, rowIndex) => (
                <View
                  key={`${String(row.timeStamp ?? "row")}-${rowIndex}`}
                  style={{
                    flexDirection: "row",
                    backgroundColor: rowIndex % 2 ? THEME.card : "#fff",
                    borderBottomWidth: 1,
                    borderColor: THEME.border,
                    minHeight: 20,
                  }}
                >
                  <View
                    style={{
                      width: 100,
                      borderRightWidth: 1,
                      borderColor: THEME.border,
                      justifyContent: "center",
                      paddingHorizontal: 5,
                    }}
                  >
                    <Text style={{ fontSize: 8 }}>{row.timeStamp != null ? formatDate(row.timeStamp, "dd MMM yyyy hh:mm a") : "-"}</Text>
                  </View>

                  {row.values.map((log, index) => {
                    const room = rooms[index];
                    const hide = hideRH(room?.categoryId);

                    return (
                      <View
                        key={index}
                        style={{
                          flex: hide ? 1 : 2,
                          flexDirection: "row",
                          borderRightWidth: 1,
                          borderColor: THEME.border,
                        }}
                      >
                        {/* Temperature */}
                        <View
                          style={{
                            flex: 1,
                            alignItems: "center",
                            justifyContent: "center",
                            borderRightWidth: hide ? 0 : 1,
                            borderColor: THEME.border,
                          }}
                        >
                          <Text style={{ fontSize: 8 }}>{formatStat(log.avgTemp, "temperature")}</Text>
                        </View>

                        {/* RH */}
                        {!hide && (
                          <View
                            style={{
                              flex: 1,
                              alignItems: "center",
                              justifyContent: "center",
                            }}
                          >
                            <Text style={{ fontSize: 8 }}>{formatStat(log.rh, "rh")}</Text>
                          </View>
                        )}
                      </View>
                    );
                  })}
                </View>
              ))}
            </View>

            {/* FOOTER */}
            <View
              fixed
              style={{
                position: "absolute",
                left: 25,
                right: 25,
                bottom: 15,
                borderTop: `1px solid ${THEME.border}`,
                paddingTop: 5,
                flexDirection: "row",
                justifyContent: "space-between",
                fontSize: 8,
                color: "#666",
              }}
            >
              <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
            </View>
          </Page>
        ));
      })}
    </Document>
  );
}
