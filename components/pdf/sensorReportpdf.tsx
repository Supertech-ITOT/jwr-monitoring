"use client";

import { Document, Image, Page, Text, View } from "@react-pdf/renderer";
import { format } from "date-fns";
import { styles } from "./style";
import { THEME } from "./theme";
import { RoomHistoricalValueDto } from "@/app/common/api.types";

const ROWS_PER_COLUMN = 30;
const COLUMNS_PER_PAGE = 3;
const ITEM_PER_PAGE = ROWS_PER_COLUMN * COLUMNS_PER_PAGE;

const HEADER_GREEN = "#35CC55";
const HEADER_TEXT = "#FFFFFF";
const BORDER_COLOR = "#D1D5DB";

type prop = {
  data: RoomHistoricalValueDto[];
  roomName: string;
  tchartImg: string;
  rchartImg: string;
  categoryName: string;
  fromDate: string;
  toDate: string;
  name: string;
};

const SensorReportPDF = ({ data, roomName, tchartImg, rchartImg, categoryName, fromDate, toDate, name }: prop) => {
  const pages = [];

  for (let start = 0; start < data.length; start += ITEM_PER_PAGE) {
    pages.push(data.slice(start, start + ITEM_PER_PAGE));
  }

  return (
    <Document>
      {/* Historical data pages */}
      {pages.map((pageRows, pageIndex) => (
        <Page key={pageIndex} size="A4" style={styles.page}>
          {/* --- Header: unchanged --- */}
          <View style={styles.header}>
            <Image src="/logo.jpg" style={styles.icon} />

            <View style={{ alignItems: "flex-end" }}>
              <Text
                style={{
                  fontSize: 10,
                  color: THEME.main,
                  fontWeight: "bold",
                }}
              >
                COLD STORAGE, JNPT, NAVI MUMBAI
              </Text>

              <Text style={{ fontSize: 9 }}>
                {format(new Date(), "dd MMM yyyy")} - {format(new Date(), "hh:mm:ss a")}
              </Text>
            </View>
          </View>

          {/* --- Report details: unchanged --- */}
          <View style={{ marginBottom: 6 }}>
            <Text style={styles.title}>{String(categoryName).toUpperCase()} REPORT</Text>

            <View style={styles.gridContainer}>
              <View style={styles.gridRow}>
                <Text style={styles.label}>Generated By : </Text>
                <Text>{name}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Room Name:</Text>
                <Text>{roomName}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Duration:</Text>
                <Text>
                  {format(new Date(fromDate), "dd-MMM-yyyy hh:mm a")} - {format(new Date(toDate), "dd-MMM-yyyy hh:mm a")}
                </Text>
              </View>
            </View>
          </View>

          {/* --- Historical table: three columns --- */}
          <View
            style={{
              flexDirection: "row",
              width: "100%",
              gap: 5,
              alignItems: "flex-start",
            }}
          >
            {Array.from({ length: COLUMNS_PER_PAGE }, (_, colIndex) => {
              const columnRows = pageRows.slice(colIndex * ROWS_PER_COLUMN, (colIndex + 1) * ROWS_PER_COLUMN);

              // Hide the complete table, including its header,
              // when this section contains no data.
              if (columnRows.length === 0) {
                return null;
              }

              return (
                <View
                  key={colIndex}
                  style={{
                    flex: 1,
                    borderWidth: 0.5,
                    borderColor: BORDER_COLOR,
                  }}
                >
                  {/* Green header with white text */}
                  <View
                    style={{
                      flexDirection: "row",
                      backgroundColor: HEADER_GREEN,
                      minHeight: 24,
                      alignItems: "center",
                      borderBottomWidth: 0.7,
                      borderColor: HEADER_TEXT,
                    }}
                  >
                    {[
                      { label: "S. No.", flex: 0.45 },
                      { label: "DATETIME", flex: 1.4 },
                      { label: "TEMP\n°C", flex: 0.9 },
                      { label: "RH\n%", flex: 0.65 },
                    ].map((col) => (
                      <Text
                        key={col.label}
                        style={{
                          flex: col.flex,
                          fontSize: 5.5,
                          fontWeight: "bold",
                          color: HEADER_TEXT,
                          textAlign: "center",
                          paddingVertical: 5,
                          paddingHorizontal: 1,
                          borderRightWidth: 0.5,
                          borderRightColor: HEADER_TEXT,
                        }}
                      >
                        {col.label}
                      </Text>
                    ))}
                  </View>

                  {/* Data rows */}
                  {columnRows.map((item, rowIndex) => {
                    const serialNumber = pageIndex * ITEM_PER_PAGE + colIndex * ROWS_PER_COLUMN + rowIndex + 1;

                    return (
                      <View
                        key={`${item.timestamp}-${serialNumber}`}
                        style={{
                          flexDirection: "row",
                          minHeight: 17,
                          alignItems: "center",
                          borderBottomWidth: 0.3,
                          borderColor: BORDER_COLOR,
                          backgroundColor: rowIndex % 2 === 0 ? "#FFFFFF" : "#F3F4F6",
                        }}
                      >
                        {/* Serial number */}
                        <Text
                          style={{
                            flex: 0.45,
                            fontSize: 5.5,
                            textAlign: "center",
                            paddingVertical: 3,
                          }}
                        >
                          {serialNumber}
                        </Text>

                        {/* Date and time */}
                        <Text
                          style={{
                            flex: 1.4,
                            fontSize: 5.5,
                            textAlign: "center",
                            paddingHorizontal: 1,
                          }}
                        >
                          {format(new Date(item.timestamp), "HH:mm dd/MM/yyyy")}
                        </Text>

                        {/* Temperature */}
                        <Text
                          style={{
                            flex: 0.9,
                            fontSize: 5.5,
                            textAlign: "center",
                          }}
                        >
                          {item.avgTemperature == null ? "-" : Number(item.avgTemperature).toFixed(2)}
                        </Text>

                        {/* Relative humidity */}
                        <Text
                          style={{
                            flex: 0.65,
                            fontSize: 5.5,
                            textAlign: "center",
                          }}
                        >
                          {item.rh == null ? "-" : Math.round(Number(item.rh))}
                        </Text>
                      </View>
                    );
                  })}
                </View>
              );
            })}
          </View>
        </Page>
      ))}

      {/* --- Overview page: unchanged --- */}
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Image src="/logo.jpg" style={styles.icon} />

          <View style={{ alignItems: "flex-end" }}>
            <Text
              style={{
                fontSize: 10,
                color: THEME.main,
                fontWeight: "bold",
              }}
            >
              COLD STORAGE, JNPT, NAVI MUMBAI
            </Text>

            <Text style={{ fontSize: 9 }}>
              {format(new Date(), "dd MMM yyyy")} - {format(new Date(), "hh:mm:ss a")}
            </Text>
          </View>
        </View>

        <Text
          style={{
            color: THEME.main,
            fontWeight: "bold",
            fontSize: 16,
            textAlign: "center",
            marginBottom: 12,
          }}
        >
          Overview
        </Text>

        <View style={{ gap: 20 }}>
          <View style={styles.chartContainer}>
            <Image src={tchartImg} style={styles.chartImg} />
          </View>

          <View style={styles.chartContainer}>
            <Image src={rchartImg} style={styles.chartImg} />
          </View>
        </View>
      </Page>
    </Document>
  );
};

export default SensorReportPDF;
