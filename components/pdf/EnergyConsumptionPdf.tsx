"use client";

import { Document, Image, Page, Text, View } from "@react-pdf/renderer";
import { format } from "date-fns";
import { styles } from "./style";
import { THEME } from "./theme";
import type { EnergyConsumptionResponse } from "@/types/consumption.types";

type FilterData = {
  categoryId: number;
  roomIds: number[];
  roomType: "POSITIVE" | "NEGATIVE";
  fromDate: string;
  toDate: string;
};

type Props = {
  data: EnergyConsumptionResponse;
  name: string;
  filter: FilterData;
};

const BORDER_COLOR = "#D1D5DB";
const HEADER_TEXT = "#FFFFFF";

const formatNumber = (value: number | null | undefined) => (value == null ? "-" : Number(value).toFixed(2));

const EnergyConsumptionPdf = ({ data, name, filter }: Props) => {
  const roomsPerPage = 25;

  const pages = [];

  for (let start = 0; start < data.rooms.length; start += roomsPerPage) {
    pages.push(data.rooms.slice(start, start + roomsPerPage));
  }

  const generatedDate = new Date();

  return (
    <Document>
      {pages.map((pageRooms, pageIndex) => (
        <Page key={pageIndex} size="A4" orientation="portrait" style={styles.page} wrap>
          {/* Header */}
          <View style={styles.header}>
            <Image src="/logo.jpg" style={styles.icon} />

            <View style={{ alignItems: "flex-end" }}>
              <Text
                style={{
                  fontSize: 10,
                  color: THEME.main,
                  fontWeight: "bold",
                }}
              >
                COLD STORAGE, JNPT, NAVI MUMBAI
              </Text>

              <Text style={{ fontSize: 9 }}>
                {format(generatedDate, "dd MMM yyyy")} - {format(generatedDate, "hh:mm:ss a")}
              </Text>
            </View>
          </View>

          {/* Report Details */}
          <View style={{ marginBottom: 10 }}>
            <Text style={styles.title}>ENERGY CONSUMPTION REPORT</Text>

            <View style={styles.gridContainer}>
              <View style={styles.gridRow}>
                <Text style={styles.label}>Generated By: </Text>
                <Text>{name}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Room Type: </Text>
                <Text>{filter.roomType}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Duration: </Text>
                <Text>
                  {format(new Date(filter.fromDate), "dd-MMM-yyyy hh:mm a")}
                  {" - "}
                  {format(new Date(filter.toDate), "dd-MMM-yyyy hh:mm a")}
                </Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Total Rooms: </Text>
                <Text>{data.rooms.length}</Text>
              </View>
            </View>
          </View>

          {/* Energy Consumption Table */}
          <View
            style={{
              width: "100%",
              borderWidth: 0.5,
              borderColor: BORDER_COLOR,
            }}
          >
            {/* Table Header */}
            <View
              style={{
                flexDirection: "row",
                backgroundColor: THEME.main,
                minHeight: 28,
                alignItems: "center",
                borderBottomWidth: 0.7,
                borderColor: HEADER_TEXT,
              }}
            >
              {[
                { label: "ROOM NAME", flex: 2 },
                { label: "COMPONENT A", flex: 1.5 },
                { label: "COMPONENT B", flex: 1.5 },
                { label: "COMPONENT C", flex: 1.5 },
                { label: "TOTAL ENERGY", flex: 1.5 },
              ].map((col) => (
                <Text
                  key={col.label}
                  style={{
                    flex: col.flex,
                    fontSize: 8,
                    fontWeight: "bold",
                    color: HEADER_TEXT,
                    textAlign: "center",
                    paddingVertical: 7,
                    paddingHorizontal: 3,
                    borderRightWidth: 0.5,
                    borderRightColor: HEADER_TEXT,
                  }}
                >
                  {col.label}
                </Text>
              ))}
            </View>

            {/* Table Rows */}
            {pageRooms.map((room, rowIndex) => {
              const serialNumber = pageIndex * roomsPerPage + rowIndex + 1;

              return (
                <View
                  key={room.roomId}
                  wrap={false}
                  style={{
                    flexDirection: "row",
                    minHeight: 24,
                    alignItems: "center",
                    borderBottomWidth: 0.3,
                    borderColor: BORDER_COLOR,
                    backgroundColor: rowIndex % 2 === 0 ? "#FFFFFF" : "#F3F4F6",
                  }}
                >
                  <Text
                    style={{
                      flex: 1.5,
                      fontSize: 8,
                      textAlign: "center",
                      paddingHorizontal: 3,
                    }}
                  >
                    {room.roomName}
                  </Text>

                  <Text
                    style={{
                      flex: 1.5,
                      fontSize: 8,
                      textAlign: "center",
                    }}
                  >
                    {formatNumber(room.componentA)}
                  </Text>

                  <Text
                    style={{
                      flex: 1.5,
                      fontSize: 8,
                      textAlign: "center",
                    }}
                  >
                    {formatNumber(room.componentB)}
                  </Text>

                  <Text
                    style={{
                      flex: 1.5,
                      fontSize: 8,
                      textAlign: "center",
                    }}
                  >
                    {formatNumber(room.componentC)}
                  </Text>

                  <Text
                    style={{
                      flex: 1.5,
                      fontSize: 8,
                      fontWeight: "bold",
                      textAlign: "center",
                    }}
                  >
                    {formatNumber(room.totalEnergy)}
                  </Text>
                </View>
              );
            })}
          </View>

          {/* Grand Total - only on the last page */}
          {pageIndex === pages.length - 1 && (
            <View
              wrap={false}
              style={{
                flexDirection: "row",
                minHeight: 30,
                alignItems: "center",
                backgroundColor: THEME.main,
                marginTop: 2,
              }}
            >
              <Text
                style={{
                  flex: 1.6,
                  color: HEADER_TEXT,
                  fontSize: 9,
                  fontWeight: "bold",
                  textAlign: "center",
                  paddingVertical: 8,
                }}
              >
                TOTAL
              </Text>

              <Text
                style={{
                  flex: 1.5,
                  color: HEADER_TEXT,
                  fontSize: 9,
                  fontWeight: "bold",
                  textAlign: "center",
                }}
              >
                {formatNumber(data.componentATotal)}
              </Text>

              <Text
                style={{
                  flex: 1.5,
                  color: HEADER_TEXT,
                  fontSize: 9,
                  fontWeight: "bold",
                  textAlign: "center",
                }}
              >
                {formatNumber(data.componentBTotal)}
              </Text>

              <Text
                style={{
                  flex: 1.5,
                  color: HEADER_TEXT,
                  fontSize: 9,
                  fontWeight: "bold",
                  textAlign: "center",
                }}
              >
                {formatNumber(data.componentCTotal)}
              </Text>

              <Text
                style={{
                  flex: 1.5,
                  color: HEADER_TEXT,
                  fontSize: 9,
                  fontWeight: "bold",
                  textAlign: "center",
                }}
              >
                {formatNumber(data.totalEnergy)}
              </Text>
            </View>
          )}

          {/* Footer */}
          <View
            fixed
            style={{
              position: "absolute",
              bottom: 12,
              left: 25,
              right: 25,
              flexDirection: "row",
              justifyContent: "space-between",
              paddingTop: 6,
              borderTopWidth: 1,
              borderTopColor: THEME.border,
            }}
          >
            <Text style={{ fontSize: 8, color: THEME.txt }}>JWR - Utility Monitoring</Text>

            <Text style={{ fontSize: 8, color: THEME.txt }} render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
          </View>
        </Page>
      ))}
    </Document>
  );
};

export default EnergyConsumptionPdf;
