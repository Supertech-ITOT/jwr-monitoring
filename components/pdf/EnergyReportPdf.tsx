"use client";

import { Document, Image, Page, Text, View } from "@react-pdf/renderer";
import { format } from "date-fns";

import { styles } from "./style";
import { THEME } from "./theme";

const ROOMS_PER_PAGE = 3;
const ROWS_PER_PAGE = 24;

const CATEGORY_WITHOUT_FREQUENCY = new Set([6, 7, 8, 9, 10, 11, 12]);

type NumericValue = number | string | null | undefined;
type ParameterType = "energy" | "current" | "voltage" | "frequency";

type EnergyLog = {
  timeStamp?: string | number | Date;
  energy?: NumericValue;
  current?: NumericValue;
  voltage?: NumericValue;
  frequency?: NumericValue;
};

type EnergyRoom = {
  roomId: number | string;
  roomName: string;
  categoryId?: number | null;
  logs: EnergyLog[];
  avgEnergy?: NumericValue;
  minEnergy?: NumericValue;
  maxEnergy?: NumericValue;
  avgCurrent?: NumericValue;
  minCurrent?: NumericValue;
  maxCurrent?: NumericValue;
  avgVoltage?: NumericValue;
  minVoltage?: NumericValue;
  maxVoltage?: NumericValue;
  avgFrequency?: NumericValue;
  minFrequency?: NumericValue;
  maxFrequency?: NumericValue;
};

type EnergyReportFilter = {
  categoryName: string;
  interval: number;
  fromDate: string;
  toDate: string;
};

type EnergyReportPDFProps = {
  data?: EnergyRoom[];
  filter: EnergyReportFilter;
  name: string;
};

type SummaryType = "avg" | "min" | "max";

type SummaryRow = {
  label: "AVG" | "MIN" | "MAX";
  type: SummaryType;
};

type ReportRow = {
  timeStamp?: string | number | Date;
  values: EnergyLog[];
};

type Parameter = {
  label: string;
  key: ParameterType;
};

const PARAMETERS: Parameter[] = [
  { label: "Energy\nkWh", key: "energy" },
  { label: "Current\nA", key: "current" },
  { label: "Voltage\nV", key: "voltage" },
  { label: "Freq\nHz", key: "frequency" },
];

const summaryRows: SummaryRow[] = [
  { label: "AVG", type: "avg" },
  { label: "MIN", type: "min" },
  { label: "MAX", type: "max" },
];

function hideFrequency(categoryId?: number | null): boolean {
  return categoryId != null && CATEGORY_WITHOUT_FREQUENCY.has(Number(categoryId));
}

function formatStat(value: NumericValue, type: ParameterType): string {
  if (value == null || value === "") return "-";

  const number = Number(value);

  if (!Number.isFinite(number)) return "-";

  if (type === "energy") return number.toFixed(1);
  if (type === "current") return number.toFixed(2);
  if (type === "voltage") return String(Math.round(number));
  if (type === "frequency") return number.toFixed(1);

  return String(number);
}

function formatDate(value: string | number | Date, pattern: string): string {
  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) return "-";

  return format(date, pattern);
}

function getSummaryValue(room: EnergyRoom, type: SummaryType, parameter: ParameterType): NumericValue {
  const key = `${type}${parameter.charAt(0).toUpperCase()}${parameter.slice(1)}` as keyof EnergyRoom;

  return room[key] as NumericValue;
}

export default function EnergyReportPDF({ data = [], filter, name }: EnergyReportPDFProps) {
  if (!data.length) {
    return <Document />;
  }

  // Split rooms into groups of three.
  const roomGroups: EnergyRoom[][] = [];

  for (let i = 0; i < data.length; i += ROOMS_PER_PAGE) {
    roomGroups.push(data.slice(i, i + ROOMS_PER_PAGE));
  }

  return (
    <Document>
      {roomGroups.map((rooms, groupIndex) => {
        const firstRoom = rooms[0];

        if (!firstRoom) return null;

        // Create rows using the first room's timestamps.
        const rows: ReportRow[] = firstRoom.logs.map((log, index) => ({
          timeStamp: log.timeStamp,
          values: rooms.map((room) => room.logs[index] ?? {}),
        }));

        // Split detail rows into pages.
        const pages: ReportRow[][] = [];

        for (let i = 0; i < rows.length; i += ROWS_PER_PAGE) {
          pages.push(rows.slice(i, i + ROWS_PER_PAGE));
        }

        return pages.map((pageRows, pageIndex) => (
          <Page key={`${groupIndex}-${pageIndex}`} size="A4" style={styles.page}>
            {/* HEADER */}
            <View style={styles.header}>
              <Image src="/logo.jpg" style={styles.icon} />

              <View style={{ alignItems: "flex-end" }}>
                <Text
                  style={{
                    fontSize: 10,
                    color: THEME.main,
                    fontWeight: "bold",
                  }}
                >
                  COLD STORAGE, JNPT, NAVI MUMBAI
                </Text>

                <Text style={{ fontSize: 9 }}>
                  {format(new Date(), "dd MMM yyyy")} - {format(new Date(), "hh:mm:ss a")}
                </Text>
              </View>
            </View>

            {/* REPORT DETAILS */}
            <Text style={styles.title}>Energy Report</Text>

            <View style={styles.gridContainer}>
              <View style={styles.gridRow}>
                <Text style={styles.label}>Generated By : </Text>
                <Text>{name}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Category :</Text>
                <Text>{filter.categoryName}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Interval :</Text>
                <Text>{filter.interval} Minutes</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Duration :</Text>
                <Text>
                  {formatDate(filter.fromDate, "dd MMM yyyy hh:mm a")} - {formatDate(filter.toDate, "dd MMM yyyy hh:mm a")}
                </Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Rooms :</Text>
                <Text>{data.map((room) => room.roomName).join(", ")}</Text>
              </View>

              <View style={styles.gridRow}>
                <Text style={styles.label}>Records :</Text>
                <Text>{rows.length}</Text>
              </View>
            </View>

            {/* DETAIL LOG */}
            <Text
              style={{
                marginTop: 0,
                marginBottom: 0,
                fontSize: 12,
                fontWeight: "bold",
                color: THEME.main,
              }}
            >
              DETAIL LOG
            </Text>

            {/* TABLE */}
            <View
              style={{
                borderWidth: 1,
                borderColor: THEME.border,
              }}
            >
              {/* HEADER ROW 1: ROOM NAMES */}
              <View
                style={{
                  flexDirection: "row",
                  backgroundColor: THEME.main,
                  borderBottomWidth: 1,
                  borderColor: THEME.border,
                  minHeight: 20,
                }}
              >
                <View
                  style={{
                    width: 100,
                    justifyContent: "center",
                    alignItems: "center",
                    borderRightWidth: 1,
                    borderColor: "#fff",
                    paddingVertical: 8,
                  }}
                >
                  <Text style={{ fontSize: 9, fontWeight: "bold", color: "#fff" }}>DATETIME</Text>
                </View>

                {rooms.map((room) => {
                  const hide = hideFrequency(room.categoryId);
                  const visibleCount = hide ? 3 : 4;

                  return (
                    <View
                      key={room.roomId}
                      style={{
                        flex: visibleCount,
                        justifyContent: "center",
                        alignItems: "center",
                        borderRightWidth: 1,
                        borderColor: "#fff",
                        paddingVertical: 8,
                      }}
                    >
                      <Text
                        style={{
                          fontSize: 9,
                          fontWeight: "bold",
                          color: "#fff",
                        }}
                      >
                        {room.roomName}
                      </Text>
                    </View>
                  );
                })}
              </View>

              {/* HEADER ROW 2: PARAMETERS */}
              <View
                style={{
                  flexDirection: "row",
                  backgroundColor: THEME.main,
                  borderBottomWidth: 1,
                  borderColor: THEME.border,
                  minHeight: 20,
                }}
              >
                <View
                  style={{
                    width: 100,
                    borderRightWidth: 1,
                    borderColor: "#fff",
                  }}
                />

                {rooms.map((room) => {
                  const visibleParameters = hideFrequency(room.categoryId)
                    ? PARAMETERS.filter((parameter) => parameter.key !== "frequency")
                    : PARAMETERS;

                  return (
                    <View
                      key={room.roomId}
                      style={{
                        flex: visibleParameters.length,
                        flexDirection: "row",
                        borderRightWidth: 1,
                        borderColor: "#fff",
                      }}
                    >
                      {visibleParameters.map((parameter, index) => (
                        <View
                          key={parameter.key}
                          style={{
                            flex: 1,
                            alignItems: "center",
                            justifyContent: "center",
                            borderRightWidth: index < visibleParameters.length - 1 ? 1 : 0,
                            borderColor: "#fff",
                            paddingVertical: 5,
                          }}
                        >
                          <Text
                            style={{
                              fontSize: 8,
                              fontWeight: "bold",
                              textAlign: "center",
                              color: "#fff",
                            }}
                          >
                            {parameter.label}
                          </Text>
                        </View>
                      ))}
                    </View>
                  );
                })}
              </View>

              {/* AVG / MIN / MAX */}
              {summaryRows.map(({ label, type }) => (
                <View
                  key={label}
                  style={{
                    flexDirection: "row",
                    backgroundColor: THEME.main,
                    borderBottomWidth: 1,
                    borderColor: THEME.border,
                    minHeight: 20,
                  }}
                >
                  <View
                    style={{
                      width: 100,
                      justifyContent: "center",
                      alignItems: "center",
                      borderRightWidth: 1,
                      borderColor: "#fff",
                    }}
                  >
                    <Text
                      style={{
                        fontSize: 8,
                        fontWeight: "bold",
                        color: "#fff",
                      }}
                    >
                      {label}
                    </Text>
                  </View>

                  {rooms.map((room) => {
                    const visibleParameters = hideFrequency(room.categoryId)
                      ? PARAMETERS.filter((parameter) => parameter.key !== "frequency")
                      : PARAMETERS;

                    return (
                      <View
                        key={room.roomId}
                        style={{
                          flex: visibleParameters.length,
                          flexDirection: "row",
                          borderRightWidth: 1,
                          borderColor: "#fff",
                        }}
                      >
                        {visibleParameters.map((parameter, index) => (
                          <View
                            key={parameter.key}
                            style={{
                              flex: 1,
                              alignItems: "center",
                              justifyContent: "center",
                              borderRightWidth: index < visibleParameters.length - 1 ? 1 : 0,
                              borderColor: "#fff",
                            }}
                          >
                            <Text
                              style={{
                                fontSize: 8,
                                fontWeight: "bold",
                                color: "#fff",
                              }}
                            >
                              {formatStat(getSummaryValue(room, type, parameter.key), parameter.key)}
                            </Text>
                          </View>
                        ))}
                      </View>
                    );
                  })}
                </View>
              ))}

              {/* BODY */}
              {pageRows.map((row, rowIndex) => (
                <View
                  key={`${String(row.timeStamp ?? "row")}-${rowIndex}`}
                  style={{
                    flexDirection: "row",
                    backgroundColor: rowIndex % 2 ? THEME.card : "#fff",
                    borderBottomWidth: 1,
                    borderColor: THEME.border,
                    minHeight: 20,
                  }}
                >
                  <View
                    style={{
                      width: 100,
                      borderRightWidth: 1,
                      borderColor: THEME.border,
                      justifyContent: "center",
                      paddingHorizontal: 5,
                    }}
                  >
                    <Text style={{ fontSize: 8 }}>{row.timeStamp != null ? formatDate(row.timeStamp, "dd MMM yyyy hh:mm a") : "-"}</Text>
                  </View>

                  {row.values.map((log, index) => {
                    const room = rooms[index];

                    const visibleParameters = hideFrequency(room?.categoryId)
                      ? PARAMETERS.filter((parameter) => parameter.key !== "frequency")
                      : PARAMETERS;

                    return (
                      <View
                        key={room?.roomId ?? index}
                        style={{
                          flex: visibleParameters.length,
                          flexDirection: "row",
                          borderRightWidth: 1,
                          borderColor: THEME.border,
                        }}
                      >
                        {visibleParameters.map((parameter, cellIndex) => (
                          <View
                            key={parameter.key}
                            style={{
                              flex: 1,
                              alignItems: "center",
                              justifyContent: "center",
                              borderRightWidth: cellIndex < visibleParameters.length - 1 ? 1 : 0,
                              borderColor: THEME.border,
                            }}
                          >
                            <Text style={{ fontSize: 8 }}>{formatStat(log[parameter.key], parameter.key)}</Text>
                          </View>
                        ))}
                      </View>
                    );
                  })}
                </View>
              ))}
            </View>

            {/* FOOTER */}
            <View
              fixed
              style={{
                position: "absolute",
                left: 25,
                right: 25,
                bottom: 15,
                borderTop: `1px solid ${THEME.border}`,
                paddingTop: 5,
                flexDirection: "row",
                justifyContent: "space-between",
                fontSize: 8,
                color: "#666",
              }}
            >
              <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
            </View>
          </Page>
        ));
      })}
    </Document>
  );
}
